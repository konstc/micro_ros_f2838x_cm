#!/usr/bin/env python3
"""Writes build_info.json and microros_f2838x_build_info.h for a library build.

build_info.json records what libmicroros.a contains: distribution, profile
limits, compiler and flags, and the exact source revisions. The header exposes
the same to the application so that the port can check at compile time
that it is built against a matching library.
"""
import argparse
import datetime
import json
import re
import subprocess
import yaml

def profile_settings(meta_path):
    with open(meta_path) as f:
        meta = json.load(f)
    settings = {}
    for package, config in meta.get('names', {}).items():
        for arg in config.get('cmake-args', []):
            m = re.fullmatch(r'-D(\w+)(?::\w+)?=(.*)', arg)
            if m:
                settings.setdefault(package, {})[m.group(1)] = m.group(2)
    return settings

def cmake_cache_values(cache_path, keys):
    values = {}
    with open(cache_path) as f:
        for line in f:
            m = re.match(r'(\w+):\w+=(.*)', line.rstrip('\n'))
            if m and m.group(1) in keys:
                values[m.group(1)] = m.group(2)
    return values

def write_header(path, info):
    rmw = info['profile_settings'].get('rmw_microxrcedds', {})
    xrce = info['profile_settings'].get('microxrcedds_client', {})
    lines = [
        '/* Generated by library_generation/scripts/write_build_info.py. Do not edit. */',
        '#ifndef MICROROS_F2838X_BUILD_INFO_H',
        '#define MICROROS_F2838X_BUILD_INFO_H',
        '',
        f'#define MICROROS_F2838X_LIB_DISTRO  "{info["distro"]}"',
        f'#define MICROROS_F2838X_LIB_PROFILE "{info["profile"]}"',
        '#define MICROROS_F2838X_LIB_TIME_T_64 1',
    ]
    for key in ('UCLIENT_CUSTOM_TRANSPORT_MTU',):
        if key in xrce:
            lines.append(f'#define MICROROS_F2838X_LIB_{key} {xrce[key]}')
    for key in sorted(rmw):
        if re.fullmatch(r'\d+', rmw[key]):
            lines.append(f'#define MICROROS_F2838X_LIB_{key} {rmw[key]}')
    lines += ['', '#endif /* MICROROS_F2838X_BUILD_INFO_H */', '']
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(lines))

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--distro', required=True)
    ap.add_argument('--profile', required=True)
    ap.add_argument('--meta', required=True, help='profile .meta file')
    ap.add_argument('--compiler', required=True, help='path to tiarmclang')
    ap.add_argument('--cmake-cache', required=True, help='CMakeCache.txt of one mcu_ws package')
    ap.add_argument('--sources', required=True, help='output of "vcs export --exact"')
    ap.add_argument('--json', required=True)
    ap.add_argument('--header', required=True)
    args = ap.parse_args()

    version = subprocess.run([args.compiler, '--version'], capture_output=True,
                             text=True, check=True).stdout.splitlines()[0].strip()
    flags = cmake_cache_values(args.cmake_cache, {'CMAKE_C_FLAGS', 'CMAKE_C_FLAGS_RELEASE'})
    with open(args.sources) as f:
        sources = (yaml.safe_load(f) or {}).get('repositories', {})

    info = {
        'distro': args.distro,
        'profile': args.profile,
        'built_at': datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds'),
        'compiler': version,
        'c_flags': ' '.join(filter(None, [flags.get('CMAKE_C_FLAGS', ''),
                                          flags.get('CMAKE_C_FLAGS_RELEASE', '')])),
        'profile_settings': profile_settings(args.meta),
        'sources': {name: {'url': repo.get('url'), 'version': repo.get('version')}
                    for name, repo in sorted(sources.items())},
    }
    with open(args.json, 'w', newline='\n') as f:
        json.dump(info, f, indent=2)
        f.write('\n')
    write_header(args.header, info)

if __name__ == '__main__':
    main()
